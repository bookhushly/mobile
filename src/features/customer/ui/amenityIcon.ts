// Words in an amenity or fact → the icon that pictures that exact thing (owner, 2026-11-15: no
// stand-ins such as a lightning bolt for a generator or sparkles for a service). First match wins,
// so the specific words come before the general ones ("Room service" before "room", "Meeting room"
// before "room"). Anything unknown gets a plain check, as Airbnb's amenity list does.
const RULES: readonly [RegExp, LucideIcon][] = [
  [/wi-?fi|internet/i, Wifi],
  [/furnish/i, Sofa],
  [/^type$/i, Building2],
  [/pool|beach/i, Waves],
  [/gym|fitness/i, Dumbbell],
  [/parking/i, CircleParking],
  [/breakfast|coffee|brunch/i, Coffee],
  [/room service|concierge|reception/i, ConciergeBell],
  [/restaurant|dining|food/i, UtensilsCrossed],
  [/\bbar\b|lounge|wine/i, Wine],
  [/spa|sauna/i, Flower2],
  [/air ?condition|a\/c/i, AirVent],
  [/\btv\b|dstv|netflix|cinema/i, Tv],
  [/laundry|washing/i, WashingMachine],
  // A generator, mains electricity or "power": the plug that power comes through.
  [/generator|electric|power/i, Plug],
  [/inverter|solar|battery/i, BatteryCharging],
  [/airport|shuttle|transfer/i, Plane],
  [/security|cctv|gated|guard|biometric|panic/i, ShieldCheck],
  [/kitchen|cook/i, CookingPot],
  [/fridge|refrigerator/i, Refrigerator],
  [/\bsafe\b|lock/i, Lock],
  [/shower|hot water/i, ShowerHead],
  [/water|borehole/i, Droplets],
  [/bath/i, Bath],
  [/business|meeting|conference|desk/i, Briefcase],
  [/phone/i, Phone],
  [/kid|child|baby/i, Baby],
  [/wheelchair|accessib/i, Accessibility],
  [/balcony|terrace|patio/i, Fence],
  [/view/i, Binoculars],
  [/rooftop/i, Sun],
  [/iron|shirt/i, Shirt],
  [/\bcar\b|charging/i, Car],
  [/guest|people|sleeps/i, Users],
  [/size|m²|sq/i, Ruler],
  [/bed|room/i, BedDouble],
];

export function amenityIcon(text: string): LucideIcon {
  return RULES.find(([re]) => re.test(text))?.[1] ?? Check;
}
